"""Map validated reference palettes to this engine's block metadata."""
from pathlib import Path
import importlib.util
ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('templates', ROOT/'tools/compile_end_city_templates.py')
templates = importlib.util.module_from_spec(spec)
spec.loader.exec_module(templates)
FACING = {'down':0,'up':1,'north':2,'south':3,'west':4,'east':5}
IDS = {'air':0,'obsidian':49,'chest':54,'ladder':65,'stained_glass':95,
       'brewing_stand':117,'ender_chest':130,'skull':144,'wall_banner':177,
       'end_rod':198,'purpur_block':201,'purpur_pillar':202,'purpur_stairs':203,
       'purpur_slab':205,'end_bricks':206,'structure_block':0}

def mapped(state):
    name=state['Name'].split(':')[1];properties=state.get('Properties',{});block=IDS[name];data=0
    if name in ('chest','ladder','ender_chest','skull','wall_banner','end_rod'):
        data=FACING[properties['facing']]
    elif name=='purpur_pillar':data={'y':0,'x':4,'z':8}[properties['axis']]
    elif name=='purpur_slab':data=8 if properties['half']=='top' else 0
    elif name=='purpur_stairs':data={'east':0,'west':1,'south':2,'north':3}[properties['facing']] | (4 if properties['half']=='top' else 0)
    elif name=='stained_glass':
        assert properties['color']=='magenta';data=2
    elif name=='brewing_stand':data=sum((1<<n) for n in range(3) if properties.get('has_bottle_'+str(n))=='true')
    return block,data

def generate():
    rooms=templates.compile_templates(ROOT/'assets/endcity')
    lines=['// Generated by tools/generate_end_city_header.py. Do not edit by hand.',
           '#pragma once','#include <cstring>','namespace EndCityTemplates {',
           'struct Run {unsigned short count;unsigned char id,data;};',
           'struct Special {unsigned char x,y,z,kind;};',
           'struct Room {const char *name;int sx,sy,sz;const Run *runs;int runCount;const Special *specials;int specialCount;};']
    records=[]
    for room in rooms:
        name=room['name'];runs=[]
        for count,state in room['runs']:
            block,data=mapped(room['palette'][state])
            if runs and runs[-1][1:]==[block,data]:runs[-1][0]+=count
            else:runs.append([count,block,data])
        specials=[]
        for special in room['specials']:
            nbt=special['nbt'];kind={'Sentry':0,'Chest':1,'Elytra':2}.get(nbt.get('metadata'))
            if nbt.get('id')=='Skull':
                assert nbt['SkullType']==5;kind=3
            elif nbt.get('id')=='Cauldron':
                assert len(nbt['Items'])==2;kind=4
            # Banner pattern is represented by the dedicated natural-city banner tile.
            if kind is not None:specials.append([*special['pos'],kind])
        lines.append('static const Run '+name+'_runs[]={'+','.join('{'+','.join(map(str,r))+'}' for r in runs)+'};')
        lines.append('static const Special '+name+'_specials[]={'+(','.join('{'+','.join(map(str,r))+'}' for r in specials) or '{0,0,0,255}')+'};')
        records.append('{"'+name+'",'+','.join(map(str,room['size']))+','+name+'_runs,'+str(len(runs))+','+name+'_specials,'+str(len(specials))+'}')
    lines+=['static const Room rooms[]={'+',\n'.join(records)+'};',
            'inline const Room *find(const char *name) {for(const auto &room:rooms) if(std::strcmp(room.name,name)==0) return &room;return nullptr;}','}']
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    import sys
    path=ROOT/'Minecraft.World/EndCityTemplates.h';content=generate()
    if '--check' in sys.argv:
        if path.read_text()!=content:raise SystemExit('Generated EndCityTemplates.h is out of date')
    else:path.write_text(content)
