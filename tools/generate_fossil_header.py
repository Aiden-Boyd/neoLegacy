"""Compile sparse original 1.12 fossil NBT. Omitted cells leave terrain intact."""
from pathlib import Path
import argparse,gzip,hashlib,json
from compile_end_city_templates import NbtReader
ROOT=Path(__file__).resolve().parents[1]
def generate():
 lines=['// Generated by tools/generate_fossil_header.py; do not edit.','#pragma once','namespace FossilTemplates {','struct Cell {unsigned char x,y,z,id,data;};','struct Template {int sx,sy,sz,count;const Cell *cells;};']
 records=[];manifest={}
 names=[f'fossil_{kind}_{i:02}{suffix}' for kind in ('spine','skull') for i in range(1,5) for suffix in ('','_coal')]
 for index,name in enumerate(names):
  p=ROOT/'assets/fossils'/f'{name}.nbt';raw=p.read_bytes();r=NbtReader(gzip.decompress(raw)).root();size=r['size'];assert len(size)==3 and all(0<n<16 for n in size)
  cells=[];seen=set()
  for b in r['blocks']:
   xyz=tuple(b['pos']);assert len(xyz)==3 and xyz not in seen and all(0<=v<size[i]for i,v in enumerate(xyz));seen.add(xyz)
   state=r['palette'][b['state']];kind=state['Name'];assert kind in ('minecraft:bone_block','minecraft:coal_ore')and 'nbt'not in b
   data={'y':0,'x':4,'z':8}[state.get('Properties',{}).get('axis','y')];cells.append((*xyz,216 if kind.endswith('bone_block')else 16,data))
  lines.append(f'static const Cell cells{index}[] = {{'+','.join('{'+','.join(map(str,c))+'}'for c in cells)+'};')
  records.append('{'+','.join(map(str,(*size,len(cells))))+f',cells{index}'+'}')
  manifest[p.name]={'sha256':hashlib.sha256(raw).hexdigest(),'size':size,'cells':len(cells)}
 lines+=['static const Template templates[] = {'+','.join(records)+'};','}']
 return '\n'.join(lines)+'\n',json.dumps({'source':'https://github.com/InventivetalentDev/minecraft-assets/tree/1.12.2/assets/minecraft/structures/fossils','templates':manifest},indent=2)+'\n'
def main():
 parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');a=parser.parse_args()
 for name,content in zip(('Minecraft.World/FossilTemplates.h','assets/fossils/provenance.json'),generate()):
  p=ROOT/name
  if a.check:assert p.read_text()==content,name+' is stale'
  else:p.write_text(content)
 print('All 16 sparse fossil templates and provenance validated')
if __name__=='__main__':main()
